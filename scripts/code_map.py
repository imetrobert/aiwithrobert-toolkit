#!/usr/bin/env python3
"""
code_map.py — writes docs/code-map.md: where everything is inside the single big index.html.

index.html is one ~400 KB file (CSS + one script). Reading it whole costs a huge amount of context, so this
generates a compact map (line numbers of every top-level function and constant, plus the CSS section
comments). Find what you need in the map, then open only that range (e.g. lines 1572-1600).
CI regenerates it on every push that changes index.html (.github/workflows/maintain.yml), so it never goes stale.
Locally:  python3 scripts/code_map.py
"""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
lines = (ROOT / "index.html").read_text(encoding="utf-8").split("\n")

style_end = next(i for i, l in enumerate(lines) if "</style>" in l) + 1
script_start = next(i for i, l in enumerate(lines) if l.strip() == "<script>") + 1
script_end = max(i for i, l in enumerate(lines) if l.strip() == "</script>") + 1

funcs, consts, css = [], [], []
for i, l in enumerate(lines, 1):
    if script_start < i < script_end:
        m = re.match(r"(?:async )?function (\w+)", l)
        if m:
            funcs.append((i, m.group(1)))
            continue
        m = re.match(r"(?:const|let|var) (\w+)\s*=", l)
        if m:
            consts.append((i, m.group(1)))
    elif i <= style_end:
        m = re.search(r"/\*\s*(.{3,70}?)\s*\*/", l)
        if m:
            css.append((i, m.group(1)))

screens = [(n, nm) for n, nm in funcs if nm.endswith("Screen")]
others = [(n, nm) for n, nm in funcs if not nm.endswith("Screen")]


def fmt(items):
    return ", ".join(f"{nm}:{n}" for n, nm in items)


out = [
    "# Code map of index.html (generated, do not edit by hand)",
    "",
    f"`index.html` has {len(lines)} lines: CSS in lines 1-{style_end}, the whole app in one `<script>` (lines {script_start}-{script_end}).",
    "Format below is `name:line`. Open only the range you need (a function is usually 10-60 lines). Regenerated by CI; run `python3 scripts/code_map.py` to refresh locally.",
    "",
    f"## Screens ({len(screens)}), each is the function that draws that screen",
    fmt(screens),
    "",
    f"## Constants and data tables ({len(consts)}): prices, brands, prompts, email templates, tool list, capability table",
    fmt(consts),
    "",
    f"## Other functions ({len(others)})",
    fmt(others),
    "",
    "## CSS section comments (top of the file)",
    "; ".join(f"{t}:{n}" for n, t in css),
    "",
]
(ROOT / "docs").mkdir(exist_ok=True)
(ROOT / "docs" / "code-map.md").write_text("\n".join(out), encoding="utf-8")
print(f"wrote docs/code-map.md: {len(screens)} screens, {len(consts)} constants, {len(others)} functions")
